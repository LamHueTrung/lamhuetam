CREATE TABLE IF NOT EXISTS public.market_prices (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Khoá nhận diện 1 chuỗi giá: source|category|brand|product|region (đã chuẩn hoá)
    series_key  TEXT NOT NULL,
    -- gold_ring: vàng cưới / nhẫn trơn | gold_bar: vàng miếng | jewelry: vàng trang sức | fuel: xăng dầu
    category    TEXT NOT NULL CHECK (category IN ('gold_ring', 'gold_bar', 'jewelry', 'fuel')),
    brand       TEXT NOT NULL,
    product     TEXT NOT NULL,
    region      TEXT NOT NULL DEFAULT '',
    buy_price   NUMERIC(14, 0),          -- giá mua vào (NULL với xăng dầu)
    sell_price  NUMERIC(14, 0),          -- giá bán ra (xăng dầu: giá bán lẻ)
    unit        TEXT NOT NULL DEFAULT '',
    source      TEXT NOT NULL DEFAULT 'webgia',
    source_at   TIMESTAMPTZ,             -- thời điểm nguồn công bố (nếu đọc được)
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Lấy lịch sử 1 chuỗi theo thời gian & lấy bản ghi mới nhất mỗi chuỗi
CREATE INDEX IF NOT EXISTS idx_market_prices_series_time
    ON public.market_prices (series_key, created_at DESC);
-- Lọc theo nhóm + khoảng thời gian (biểu đồ 7/30/90 ngày)
CREATE INDEX IF NOT EXISTS idx_market_prices_category_time
    ON public.market_prices (category, created_at DESC);

-- View: bản ghi mới nhất của mỗi chuỗi giá
CREATE OR REPLACE VIEW public.market_prices_latest
WITH (security_invoker = true) AS
SELECT DISTINCT ON (series_key)
       id, series_key, category, brand, product, region,
       buy_price, sell_price, unit, source_at, created_at
FROM public.market_prices
ORDER BY series_key, created_at DESC;

-- RLS: ai cũng đọc được, KHÔNG có policy INSERT/UPDATE/DELETE => client không ghi được
ALTER TABLE public.market_prices ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "market_prices_public_read" ON public.market_prices;
CREATE POLICY "market_prices_public_read"
    ON public.market_prices
    FOR SELECT
    TO anon, authenticated
    USING (true);

GRANT SELECT ON public.market_prices        TO anon, authenticated;
GRANT SELECT ON public.market_prices_latest TO anon, authenticated;

